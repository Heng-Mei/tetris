// 按 类型/起止状态 取踢墙偏移序列
export function kickList(system, type, from, to, is180) {
  if (type === 'O') return [[0, 0]];
  if (is180) {
    return (system.kicks && system.kicks.half) || [[0, 0]];
  }
  const table = (type === 'I' && system.kicks && system.kicks.I) || system.kicks.standard;
  return table[`${from}>${to}`] || table['*'] || [[0, 0]];
}
